"""Compile the paper with pdflatex + bibtex.

Usage: python experiments/build_paper.py [article|ieee|all]   (default: all)
  article: paper/main.tex           -> paper/main.pdf (single-column preprint)
  ieee:    paper/ieee/main_ieee.tex -> paper/ieee/main_ieee.pdf (IEEEtran, two-column journal)

Finds pdflatex on PATH or in the default MiKTeX user install location. For the IEEE version,
paper/ieee/refs_ieee.bib is generated from paper/references.bib: IEEEtran.bst ignores the doi
field, so each DOI is added as a note ("doi: ...") as in IEEE reference style.
"""
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAPER = os.path.join(ROOT, "paper")
IEEE = os.path.join(PAPER, "ieee")


def find(exe):
    p = shutil.which(exe)
    if p:
        return p
    cand = os.path.expandvars(rf"%LOCALAPPDATA%\Programs\MiKTeX\miktex\bin\x64\{exe}.exe")
    return cand if os.path.exists(cand) else None


def make_ieee_bib():
    """Copy references.bib, adding note = {doi: ...} to every entry that has a doi field."""
    with open(os.path.join(PAPER, "references.bib"), encoding="utf-8") as fh:
        src = fh.read()
    out = ["% Generated by experiments/build_paper.py from ../references.bib; do not edit.\n"]
    for block in re.split(r"(?=^@)", src, flags=re.M):
        m = re.search(r"doi\s*=\s*\{([^}]*)\}", block)
        if block.startswith("@") and m and "note" not in block:
            doi = m.group(1)
            note = "  note    = {doi: \\href{https://doi.org/" + doi + "}{" + doi + "}}"
            body = block.rstrip()
            assert body.endswith("}"), body[-40:]
            body = body[:-1].rstrip()
            if not body.endswith(","):
                body += ","
            block = body + "\n" + note + "\n}\n\n"
        if block.startswith("@"):
            out.append(block)
    with open(os.path.join(IEEE, "refs_ieee.bib"), "w", encoding="utf-8") as fh:
        fh.write("".join(out))


def compile_tex(folder, stem, pdflatex, bibtex):
    def run(cmd):
        subprocess.run(cmd, cwd=folder, check=True, stdout=subprocess.DEVNULL)
    run([pdflatex, "-interaction=nonstopmode", "-halt-on-error", stem + ".tex"])
    run([bibtex, stem])
    run([pdflatex, "-interaction=nonstopmode", "-halt-on-error", stem + ".tex"])
    run([pdflatex, "-interaction=nonstopmode", "-halt-on-error", stem + ".tex"])
    print(os.path.relpath(os.path.join(folder, stem + ".pdf"), ROOT), "written")


def main(which="all"):
    pdflatex, bibtex = find("pdflatex"), find("bibtex")
    if not pdflatex or not bibtex:
        sys.exit("pdflatex/bibtex not found. Install a TeX distribution (e.g. MiKTeX or TeX Live), "
                 "then run: cd paper && pdflatex main && bibtex main && pdflatex main && pdflatex main")
    if which in ("article", "all"):
        compile_tex(PAPER, "main", pdflatex, bibtex)
    if which in ("ieee", "all"):
        make_ieee_bib()
        compile_tex(IEEE, "main_ieee", pdflatex, bibtex)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "all")
